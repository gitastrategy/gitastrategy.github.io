// Snapshots the public "LinkedIn posts" Google Sheet into src/data/linkedin-posts.ts
// Run: bun run scripts/sync-linkedin.mjs
import { writeFileSync } from "node:fs";

const SHEET_ID = "1bYXRX8aThHDZdj0kslXDK-EdzR2-KjXJq4c880Q6Pkg";
const url = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&gid=0`;

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false; }
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c !== "\r") field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const slugify = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 80);

const res = await fetch(url);
if (!res.ok) throw new Error(`Sheet fetch failed: ${res.status}`);
const rows = parseCsv(await res.text());
const header = rows.shift().map((h) => h.trim());
const idx = (name) => header.indexOf(name);

const posts = rows
  .filter((r) => r.length > 1 && r[idx("Title")]?.trim())
  .map((r) => ({
    id: r[idx("PostId")]?.trim(),
    date: r[idx("Date")]?.trim(),
    title: r[idx("Title")]?.trim(),
    category: r[idx("Category")]?.trim(),
    subCategory: r[idx("SubCategory")]?.trim(),
    topic: r[idx("CoreTopic")]?.trim(),
    trend: r[idx("Trend")]?.trim(),
    summary: r[idx("TrendSummary")]?.trim(),
    content: r[idx("Content")]?.trim(),
    imageUrl: r[idx("ImageUrl")]?.trim(),
    urn: r[idx("LinkedInPostURN")]?.trim(),
  }))
  .filter((p) => p.content)
  .map((p) => ({ ...p, slug: slugify(p.title) }));

const seen = new Set();
for (const p of posts) {
  let s = p.slug, n = 2;
  while (seen.has(s)) s = `${p.slug}-${n++}`;
  seen.add(s); p.slug = s;
}

const banner = `// AUTO-GENERATED by scripts/sync-linkedin.mjs — do not edit by hand.\n// Source: Google Sheet ${SHEET_ID} (Date, Title, LinkedInPostURN, Content ...)\n`;
const body = `${banner}
export type LinkedInPost = {
  id: string;
  slug: string;
  date: string;
  title: string;
  category: string;
  subCategory: string;
  topic: string;
  trend: string;
  summary: string;
  content: string;
  imageUrl: string;
  urn: string;
};

export const linkedInPosts: LinkedInPost[] = ${JSON.stringify(posts, null, 2)};

export function sortedLinkedInPosts(): LinkedInPost[] {
  const time = (d: string) => {
    const t = Date.parse(d.replace(/-/g, " "));
    return Number.isNaN(t) ? 0 : t;
  };
  return [...linkedInPosts].sort((a, b) => time(b.date) - time(a.date));
}

export function findLinkedInPost(slug: string): LinkedInPost | undefined {
  return linkedInPosts.find((p) => p.slug === slug);
}
`;
writeFileSync(new URL("../src/data/linkedin-posts.ts", import.meta.url), body);
console.log(`Wrote ${posts.length} posts`);
